const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1200, height: 800 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const p = await ctx.newPage();
  await p.addInitScript(() => { if (!localStorage.getItem('coolant.settings')) localStorage.setItem('coolant.settings', JSON.stringify({ plain: false, guideSeen: true })); });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type()==='error' && errs.push(m.text()));
  await p.goto(process.env.BASE || 'http://localhost:4173');
  await p.waitForFunction(() => document.querySelectorAll('tbody tr').length > 5);
  await p.getByRole('button', { name: 'Logs', exact: true }).click();
  await p.waitForFunction(() => document.querySelectorAll('.logtable tbody tr.static').length > 0, null, { timeout: 10000 });
  console.log('commands are listed:', (await p.locator('.logtable').innerText()).includes('adb devices -l'));
  await p.waitForFunction(() => /×\d+/.test(document.querySelector('.logtable').innerText), null, { timeout: 15000 });
  console.log('repeated commands are counted, not repeated:', await p.locator('.logtable tbody tr', { hasText: 'adb devices -l' }).count() === 1);
  await p.waitForFunction(() => document.querySelector('.bad-mark'), null, { timeout: 20000 });
  console.log('a failed command is marked:', await p.locator('.bad-mark').count() >= 1);
  await p.getByLabel('Only problems').check();
  const rows = await p.locator('.logtable tbody tr.static').count();
  console.log('only problems filter:', rows >= 1 && (await p.locator('.logtable tbody tr.static .ok-mark').count()) === 0);
  await p.getByLabel('Only problems').uncheck();
  await p.getByRole('button', { name: 'Copy' }).click();
  await p.getByText('Copied.').waitFor();
  console.log('copy puts the text on the clipboard:', (await p.evaluate(() => navigator.clipboard.readText())).includes('adb devices -l'));
  await p.getByRole('button', { name: 'Pause' }).click();
  const before = await p.locator('.logtable').innerText(); await p.waitForTimeout(3500);
  console.log('pause freezes the list:', before === await p.locator('.logtable').innerText());
  await p.getByRole('button', { name: 'Resume' }).click();
  await p.getByRole('button', { name: 'Clear' }).click();
  await p.waitForFunction(() => /Nothing yet|adb devices/.test(document.querySelector('.logtable').innerText));
  console.log('errors', errs); await browser.close();
})();
