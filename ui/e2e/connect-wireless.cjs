const { chromium } = require('playwright');
const SHOT = process.argv[2];
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1100, height: 760 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type()==='error' && errs.push(m.text()));
  await p.goto((process.env.BASE || 'http://localhost:4173'));
  await p.waitForFunction(() => document.querySelectorAll('tbody tr').length > 5);
  const opts = async () => p.locator('select[aria-label=Device] option').allTextContents();
  console.log('device options:', await opts());
  await p.getByRole('button', { name: 'Connect…' }).click();
  const dlg = p.getByRole('dialog', { name: 'Connect device' });
  await p.waitForFunction(() => document.querySelector('.modal input[placeholder="192.168.1.20:37099"]').value !== '');
  console.log('autofilled pairing:', await dlg.getByPlaceholder('192.168.1.20:37099').inputValue(), '| connect:', await dlg.getByPlaceholder('192.168.1.20:41231').inputValue());
  const pairBtn = dlg.getByRole('button', { name: 'Pair', exact: true });
  console.log('pair disabled w/o code:', await pairBtn.isDisabled());
  await dlg.getByPlaceholder('123456').fill('12ab34x'); console.log('code keeps digits only:', await dlg.getByPlaceholder('123456').inputValue());
  await dlg.getByPlaceholder('123456').fill('000000'); await pairBtn.click();
  await p.waitForSelector('.status.error'); console.log('wrong code ->', (await dlg.locator('.status.error').innerText()).slice(0, 60));
  await dlg.getByPlaceholder('123456').fill('123456'); await pairBtn.click();
  await p.waitForSelector('.status.ok', { timeout: 6000 });
  await p.waitForFunction(() => document.querySelector('.status.ok')?.textContent.includes('connected to'), null, { timeout: 6000 });
  console.log('pair + auto-connect ->', (await dlg.locator('.status.ok').innerText()).slice(0, 70));
  await dlg.getByPlaceholder('192.168.1.20:41231').fill('192.168.1.20:1'); await dlg.getByRole('button', { name: 'Connect', exact: true }).click();
  await p.waitForSelector('.status.error'); console.log('refused ->', (await dlg.locator('.status.error').innerText()).slice(0, 40));
  await dlg.getByRole('button', { name: 'From USB' }).click();
  await dlg.getByRole('button', { name: 'Switch to Wi-Fi' }).click(); await p.waitForSelector('.status.ok', { timeout: 6000 });
  console.log('usb->wifi ->', (await dlg.locator('.status.ok').innerText()).slice(0, 50));
  await dlg.getByRole('button', { name: 'QR code' }).click(); await dlg.getByRole('button', { name: 'Start' }).click();
  await p.waitForSelector('.qr svg'); console.log('qr shown: true');
  await p.screenshot({ path: SHOT });
  await dlg.getByRole('button', { name: 'Cancel' }).click(); console.log('qr hidden after cancel:', await p.locator('.qr').count() === 0);
  await dlg.getByRole('button', { name: 'Saved' }).click(); console.log('saved entries:', await dlg.locator('.saved').count());
  await dlg.getByRole('button', { name: 'Close' }).click();
  await p.waitForTimeout(5500);
  console.log('device options after:', await opts());
  const wifi = p.locator('select[aria-label=Device] option', { hasText: 'mock, Wi-Fi' }).first();
  await p.selectOption('select[aria-label=Device]', await wifi.getAttribute('value'));
  await p.waitForFunction(() => document.querySelectorAll('tbody tr').length > 5);
  console.log('disconnect button visible for wifi:', await p.getByRole('button', { name: 'Disconnect' }).count() === 1);
  console.log('errors', errs); await b.close();
})();
